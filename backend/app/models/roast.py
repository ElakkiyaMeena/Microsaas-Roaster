"""Roast model: an AI-generated code review for a submission."""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING, Any

import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.sql import func

from app.database import Base
from app.models.base import enum_column_type
from app.models.enums import RoastIntensity, RoastStatus

if TYPE_CHECKING:
    from app.models.share_link import ShareLink
    from app.models.submission import Submission
    from app.models.user import User


class Roast(Base):
    """A roast (structured code review) generated by OpenAI for a submission."""

    __tablename__ = "roasts"
    __table_args__ = (sa.Index("ix_roasts_user_id_created_at", "user_id", "created_at"),)

    id: Mapped[int] = mapped_column(sa.Integer, primary_key=True)
    submission_id: Mapped[int] = mapped_column(
        sa.ForeignKey("submissions.id", ondelete="CASCADE"), index=True, nullable=False
    )
    user_id: Mapped[int] = mapped_column(
        sa.ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False
    )
    intensity: Mapped[RoastIntensity] = mapped_column(
        enum_column_type(RoastIntensity), nullable=False
    )
    status: Mapped[RoastStatus] = mapped_column(
        enum_column_type(RoastStatus),
        default=RoastStatus.PENDING,
        server_default=RoastStatus.PENDING.value,
        nullable=False,
    )
    score: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    headline: Mapped[str | None] = mapped_column(sa.String(280), nullable=True)
    summary: Mapped[str | None] = mapped_column(sa.Text, nullable=True)
    issues: Mapped[list[dict[str, Any]]] = mapped_column(sa.JSON, default=list, nullable=False)
    strengths: Mapped[list[str]] = mapped_column(sa.JSON, default=list, nullable=False)
    model: Mapped[str | None] = mapped_column(sa.String(100), nullable=True)
    prompt_tokens: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    completion_tokens: Mapped[int | None] = mapped_column(sa.Integer, nullable=True)
    error_message: Mapped[str | None] = mapped_column(sa.String(500), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), server_default=func.now(), index=True, nullable=False
    )
    completed_at: Mapped[datetime | None] = mapped_column(sa.DateTime(timezone=True), nullable=True)

    submission: Mapped[Submission] = relationship(back_populates="roasts")
    user: Mapped[User] = relationship(back_populates="roasts")
    share_link: Mapped[ShareLink | None] = relationship(
        back_populates="roast",
        uselist=False,
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    def __repr__(self) -> str:
        return f"<Roast id={self.id} submission_id={self.submission_id} status={self.status}>"
